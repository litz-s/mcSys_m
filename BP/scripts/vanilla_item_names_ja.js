export function fallbackItemNameJa(typeId) {
    const raw = String(typeId ?? "");
    if (VANILLA_ITEM_NAMES_JA[raw]) return VANILLA_ITEM_NAMES_JA[raw];

    const withoutNamespace = raw.includes(":") ? raw.split(":").slice(1).join(":") : raw;
    return withoutNamespace
        .replace(/_/g, " ")
        .replace(/\b\w/g, (c) => c.toUpperCase());
}

export function getItemNameJa(typeId) {
    return VANILLA_ITEM_NAMES_JA[String(typeId ?? "")] ?? fallbackItemNameJa(typeId);
}
